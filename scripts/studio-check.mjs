import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 200)); });
page.on('pageerror', e => errors.push('PAGEERROR: ' + String(e).slice(0, 300)));
await page.addInitScript(() => { try { localStorage.setItem('iris-onboarding-complete', 'true'); } catch {} });
await page.goto('http://localhost:3000/workspace/visualize', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForTimeout(2500);
console.log('TITLE:', await page.textContent('h2'));
console.log('TOOLBAR preset:', await page.locator('.viz-studio-toolbar select').first().inputValue().catch(() => 'none'));
console.log('DOCK panels:', await page.locator('.dv-dockview .dv-view').count());
console.log('EMPTY:', await page.locator('.viz-empty-hero').count());
await page.screenshot({ path: 'artifacts/visualization/studio-desktop-dark.png' });
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
await mobile.goto('http://localhost:3000/workspace/visualize', { waitUntil: 'networkidle', timeout: 60000 });
await mobile.waitForTimeout(1500);
console.log('MOBILE tabbed:', await mobile.locator('.viz-studio-mobile').count(), '| dock visible:', await mobile.locator('.viz-studio-dock').isVisible().catch(() => false));
await mobile.screenshot({ path: 'artifacts/visualization/studio-mobile.png' });
console.log('ERRORS:', errors.length ? errors.join(' | ') : 'none');
await browser.close();
